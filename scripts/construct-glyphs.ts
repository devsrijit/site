// Writes lib/construct/glyphs.ts: the outlines of the display face at the
// instance the site uses (Archivo, wdth 62, wght 800), in font units.
//
// The source is the variable font that next/font puts into the build, so the
// outlines are the same file the browser draws. Run a build first, then:
//   bun scripts/construct-glyphs.ts
//
// Coordinates keep the font's y-up axis. The construction layer flips them.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import * as fontkit from "fontkit";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-.&";
const AXES = { wdth: 62, wght: 800 };

/** Finds the latin Archivo face in the built CSS: it is the one for U+00-FF. */
function findFont(): string {
  const cssDir = join(ROOT, ".next/static/chunks");
  for (const f of readdirSync(cssDir).filter((n) => n.endsWith(".css"))) {
    const css = readFileSync(join(cssDir, f), "utf8");
    for (const face of css.split("@font-face")) {
      if (!face.includes("font-family:Archivo")) continue;
      if (!face.includes("unicode-range:U+??")) continue;
      const m = face.match(/url\(\.\.\/media\/([^)]+\.woff2)\)/);
      if (m) return join(ROOT, ".next/static/media", m[1]);
    }
  }
  throw new Error("No latin Archivo face in .next/static/chunks/*.css. Run `bun run build` first.");
}

const r = (n: number) => Math.round(n * 10) / 10;

const file = process.argv[2] ?? findFont();
const base = fontkit.create(readFileSync(file)) as fontkit.Font;
const font = base.getVariation(AXES);

const glyphs: Record<string, { adv: number; d: string }> = {};
for (const ch of CHARS) {
  const g = font.glyphForCodePoint(ch.codePointAt(0)!);
  const parts: string[] = [];
  for (const c of g.path.commands) {
    const a = c.args.map(r);
    switch (c.command) {
      case "moveTo":
        parts.push(`M${a.join(" ")}`);
        break;
      case "lineTo":
        parts.push(`L${a.join(" ")}`);
        break;
      case "quadraticCurveTo":
        parts.push(`Q${a.join(" ")}`);
        break;
      case "bezierCurveTo":
        parts.push(`C${a.join(" ")}`);
        break;
      case "closePath":
        parts.push("Z");
        break;
    }
  }
  glyphs[ch] = { adv: r(g.advanceWidth), d: parts.join("") };
}

const H = font.glyphForCodePoint(72).bbox;
const meta = {
  upm: font.unitsPerEm,
  ascent: font.hhea.ascent,
  descent: font.hhea.descent,
  capHeight: r(H.maxY),
};

const out = `// Generated by scripts/construct-glyphs.ts. Do not edit.
// Archivo (OFL), wdth ${AXES.wdth}, wght ${AXES.wght}, from the variable font in the build.
// Units are font units with y up. Commands: M, L, Q, C, Z.

export const FONT = ${JSON.stringify(meta)} as const;

export const GLYPHS: Record<string, { adv: number; d: string }> = ${JSON.stringify(glyphs, null, 0)
  .replace(/\},"/g, '},\n  "')
  .replace(/^\{/, "{\n  ")
  .replace(/\}$/, ",\n}")};
`;

writeFileSync(join(ROOT, "lib/construct/glyphs.ts"), out);
console.log(`wrote ${CHARS.length} glyphs from ${file}`, meta);
console.log("SRIJIT GHOSH advance (em):", [..."SRIJIT GHOSH"].reduce((s, c) => s + (c === " " ? font.glyphForCodePoint(32).advanceWidth : glyphs[c].adv), 0) / font.unitsPerEm);
