// Writes lib/og/die.ts: the 1-bit die photo as one SVG path.
// Source: public/avatar-dsphere-100.png (100 x 100, 1-bit grayscale).
// Each run of white pixels in a row becomes one rectangle, so the path
// drawn at a whole-number scale stays pixel-exact in the share card.
// Run: bun scripts/og-die.ts

import { readFileSync, writeFileSync } from "node:fs";
import { inflateSync } from "node:zlib";

const png = readFileSync("public/avatar-dsphere-100.png");
let off = 8;
let w = 0;
let h = 0;
const idat: Buffer[] = [];
while (off < png.length) {
  const len = png.readUInt32BE(off);
  const type = png.toString("ascii", off + 4, off + 8);
  const data = png.subarray(off + 8, off + 8 + len);
  if (type === "IHDR") {
    w = data.readUInt32BE(0);
    h = data.readUInt32BE(4);
    if (data[8] !== 1 || data[9] !== 0 || data[12] !== 0) {
      throw new Error("expected a 1-bit grayscale, non-interlaced PNG");
    }
  }
  if (type === "IDAT") idat.push(data);
  off += 12 + len;
}

const raw = inflateSync(Buffer.concat(idat));
const stride = Math.ceil(w / 8);
const rows: Uint8Array[] = [];
let prev = new Uint8Array(stride);
for (let y = 0; y < h; y++) {
  const f = raw[y * (stride + 1)];
  const line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
  const cur = new Uint8Array(stride);
  for (let i = 0; i < stride; i++) {
    const a = i > 0 ? cur[i - 1] : 0;
    const b = prev[i];
    const c = i > 0 ? prev[i - 1] : 0;
    let p = 0;
    if (f === 1) p = a;
    else if (f === 2) p = b;
    else if (f === 3) p = (a + b) >> 1;
    else if (f === 4) {
      const pa = Math.abs(b - c);
      const pb = Math.abs(a - c);
      const pc = Math.abs(a + b - 2 * c);
      p = pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
    }
    cur[i] = (line[i] + p) & 0xff;
  }
  rows.push(cur);
  prev = cur;
}

const bit = (x: number, y: number) => (rows[y][x >> 3] >> (7 - (x & 7))) & 1;

let d = "";
let lit = 0;
for (let y = 0; y < h; y++) {
  let x = 0;
  while (x < w) {
    if (!bit(x, y)) {
      x++;
      continue;
    }
    const x0 = x;
    while (x < w && bit(x, y)) x++;
    d += `M${x0} ${y}h${x - x0}v1h${x0 - x}z`;
    lit += x - x0;
  }
}

const out = `// Generated by scripts/og-die.ts from public/avatar-dsphere-100.png. Do not edit.
// The white pixels of the 1-bit die photo, one rectangle per run, in a
// ${w} x ${h} grid. ${lit} of ${w * h} pixels are lit.

export const DIE_SIZE = ${w};

export const DIE_PATH =
  "${d}";
`;
writeFileSync("lib/og/die.ts", out);
console.log(`die: ${w}x${h}, ${lit} lit pixels, ${d.length} path chars`);
